#!/usr/bin/env python3
"""Regenerate Sources/Bench/Remote/RemoteWebApp.swift from the phone app's source files.

The web files live in RemoteWeb/ (index.html, app.js, app.css,
manifest.webmanifest, sw.js). Edit those, then run:

    python3 Scripts/embed-remote-web.py

The Swift file is generated: never edit it by hand. Pass --check to fail (exit 1)
when the committed Swift file is out of date, without writing anything.

To keep the app small, app.js, app.css and sw.js are embedded with leading indentation,
blank lines and full-line comments removed (nothing else changes, so the code
behaves the same). The stripped JS is syntax-checked with node when node exists.
Pass --readable to embed the files exactly as they are.

It also embeds Resources/AppIcon.icon/Assets/bench-glyph.png as base64
(RemoteWebApp.iconGlyph). The raw glyph is not in the app bundle, and
RemoteIcon draws the Home Screen icons from it at run time.
"""
import base64
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "RemoteWeb"
OUT = ROOT / "Sources/Bench/Remote/RemoteWebApp.swift"
GLYPH = ROOT / "Resources/AppIcon.icon/Assets/bench-glyph.png"

# (served path, source file, Swift constant, content type)
FILES = [
    ("/", "index.html", "indexHTML", "text/html; charset=utf-8"),
    ("/app.js", "app.js", "appJS", "text/javascript; charset=utf-8"),
    ("/app.css", "app.css", "appCSS", "text/css; charset=utf-8"),
    ("/manifest.webmanifest", "manifest.webmanifest", "manifest", "application/manifest+json"),
    ("/sw.js", "sw.js", "serviceWorkerJS", "text/javascript; charset=utf-8"),
]


def strip(src: str, body: str) -> str:
    """Remove indentation, blank lines and full-line comments from app.js / app.css."""
    if src.endswith(".js"):
        full_line_comment = re.compile(r"^(//.*|/\*.*\*/)$")
    elif src.endswith(".css"):
        full_line_comment = re.compile(r"^/\*.*\*/$")
    else:
        return body
    out = []
    for line in body.splitlines():
        line = line.strip()
        if line and not full_line_comment.match(line):
            out.append(line)
    text = "\n".join(out) + "\n"
    if src.endswith(".js") and shutil.which("node"):
        with tempfile.TemporaryDirectory() as d:
            f = pathlib.Path(d) / "check.mjs"
            f.write_text(text, encoding="utf-8")
            r = subprocess.run(["node", "--check", str(f)], capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"stripped {src} no longer parses:\n{r.stderr}")
    return text


def literal(body: str) -> str:
    """A multi-line raw string literal that cannot be closed or interpolated by the body."""
    n = 1
    while ('"""' + "#" * n) in body or ("\\" + "#" * n) in body:
        n += 1
    hashes = "#" * n
    # Content sits at column 0 and so does the closing delimiter, so nothing is stripped.
    return f'{hashes}"""\n{body.rstrip(chr(10))}\n"""{hashes}'


def generate() -> str:
    lines = [
        "import Foundation",
        "",
        "// GENERATED by Scripts/embed-remote-web.py from RemoteWeb/.",
        "// Edit the files there and rerun the script; do not edit this file by hand.",
        "//",
        "// The phone app that RemoteServer serves: plain HTML, JS and CSS with no inline",
        "// script or style and no third-party code, so the strict CSP holds.",
        "",
        "enum RemoteWebApp {",
        '    /// Path -> (content type, body). Paths: "/", "/app.js", "/app.css", "/manifest.webmanifest", "/sw.js".',
        "    static let files: [String: (contentType: String, body: String)] = [",
    ]
    for path, _src, const, ctype in FILES:
        lines.append(f'        "{path}": (contentType: "{ctype}", body: {const}),')
    lines += [
        "    ]",
        "",
        "    /// Ready-made PNG icons. nil: the server draws them from `iconGlyph` (RemoteIcon).",
        "    static let icon180: Data? = nil",
        "    static let icon512: Data? = nil",
        "",
        "    /// The bench glyph (1024 x 1024 PNG, with alpha) the Home Screen icons are drawn from.",
        "    static let iconGlyph: Data = Data(base64Encoded: iconGlyphBase64, options: .ignoreUnknownCharacters) ?? Data()",
        "",
    ]
    for _path, src, const, _ctype in FILES:
        body = (WEB / src).read_text(encoding="utf-8")
        if "--readable" not in sys.argv:
            body = strip(src, body)
        lines.append(f"    // {src}")
        lines.append(f"    private static let {const}: String = " + literal(body))
        lines.append("")
    lines.append("    // Resources/AppIcon.icon/Assets/bench-glyph.png")
    lines.append('    private static let iconGlyphBase64: String = """')
    encoded = base64.b64encode(GLYPH.read_bytes()).decode("ascii")
    lines += [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    lines.append('"""')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run Scripts/embed-remote-web.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    sizes = {f[0]: len(strip(f[1], (WEB / f[1]).read_text(encoding="utf-8")).encode()) if "--readable" not in sys.argv
             else (WEB / f[1]).stat().st_size for f in FILES}
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {v} B" for k, v in sizes.items()) + f", total {sum(sizes.values())} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
